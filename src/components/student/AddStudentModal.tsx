'use client';

import React, { useState } from 'react';
import { X, UserPlus, Sparkles, QrCode, CheckCircle2 } from 'lucide-react';
import { NexoCredential, VerificationPresentationPayload } from '@/lib/types';
import { createSelectivePresentation, getDisclosureOptions } from '@/lib/sd-jwt-helper';

interface AddStudentModalProps {
  isOpen: boolean;
  onClose: () => void;
  holderAddress: string;
  holderPrivateKey?: string;
  onStudentCreated: (newCredential: NexoCredential, autoGeneratedQR: VerificationPresentationPayload) => void;
}

export function AddStudentModal({
  isOpen,
  onClose,
  holderAddress,
  holderPrivateKey,
  onStudentCreated,
}: AddStudentModalProps) {
  const [fullName, setFullName] = useState('Devansh Gupta');
  const [studentId, setStudentId] = useState('IITB-2024-006');
  const [degree, setDegree] = useState('Bachelor of Technology');
  const [major, setMajor] = useState('Artificial Intelligence and Data Science');
  const [cgpa, setCgpa] = useState('8.92');
  const [institutionName, setInstitutionName] = useState('IIT Bombay');
  const [isSubmitting, setIsSubmitting] = useState(false);

  if (!isOpen) return null;

  const handleSubmit = async (e: React.FormEvent) => {
    e.preventDefault();
    setIsSubmitting(true);

    const parsedCgpa = parseFloat(cgpa) || 8.0;
    const cgpaAbove8 = parsedCgpa >= 8.0;

    const payload = {
      type: 'academic',
      title: `${degree} in ${major}`,
      issuerName: institutionName,
      issuerAddress: '0x1234567890123456789012345678901234567890',
      issuerCategory: 'University',
      claims: {
        student_id: studentId,
        full_name: fullName,
        degree: degree,
        major: major,
        graduation_year: 2024,
        cgpa: parsedCgpa,
        cgpa_above_8: cgpaAbove8,
        institution_name: institutionName,
        issue_date: new Date().toISOString().split('T')[0],
      },
    };

    try {
      // 1. Post to API to create the credential
      const res = await fetch('/api/credentials', {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify(payload),
      });

      const data = await res.json();
      if (!data.success || !data.credential) {
        throw new Error(data.error || 'Failed to create student');
      }

      const createdCredential: NexoCredential = data.credential;

      // 2. Auto-generate the Selective Disclosure Presentation & QR Payload!
      const disclosureOptions = getDisclosureOptions(createdCredential);
      // Ensure CGPA >= 8 is selected and exact CGPA is masked
      const optionsWithPredicate = disclosureOptions.map((opt) => {
        if (opt.key === 'cgpa_above_8') return { ...opt, disclosed: true };
        if (opt.key === 'cgpa') return { ...opt, disclosed: false }; // masked for privacy
        if (opt.key === 'student_id') return { ...opt, disclosed: false }; // masked for privacy
        return opt;
      });

      const autoPresentation = await createSelectivePresentation(
        createdCredential,
        optionsWithPredicate,
        holderAddress,
        holderPrivateKey,
        'Campus Recruitment Verification',
        60
      );

      // 3. Callback with the new credential and pre-generated QR code!
      onStudentCreated(createdCredential, autoPresentation);
      onClose();
    } catch (err: any) {
      console.error('Error creating student:', err);
      alert('Error creating student credential: ' + err.message);
    } finally {
      setIsSubmitting(false);
    }
  };

  return (
    <div className="fixed inset-0 z-50 flex items-center justify-center p-4 bg-slate-900/60 backdrop-blur-sm animate-fadeIn">
      <div className="bg-white rounded-3xl max-w-lg w-full max-h-[92vh] flex flex-col shadow-2xl border border-slate-100 overflow-hidden">
        {/* Header */}
        <div className="p-6 border-b border-slate-100 flex items-center justify-between bg-slate-50/50">
          <div className="flex items-center gap-3">
            <div className="p-2 rounded-xl bg-indigo-50 text-indigo-600 border border-indigo-100">
              <UserPlus className="w-5 h-5" />
            </div>
            <div>
              <h2 className="text-xl font-bold text-slate-900">Issue New Student Credential</h2>
              <p className="text-xs text-slate-500">Auto-generates verification QR code upon creation</p>
            </div>
          </div>
          <button
            onClick={onClose}
            className="p-2 text-slate-400 hover:text-slate-600 rounded-full hover:bg-slate-100 transition"
          >
            <X className="w-5 h-5" />
          </button>
        </div>

        {/* Form Body */}
        <form onSubmit={handleSubmit} className="p-6 overflow-y-auto space-y-4">
          <div className="grid grid-cols-2 gap-3">
            <div>
              <label className="text-xs font-semibold text-slate-700 block mb-1">Full Student Name</label>
              <input
                type="text"
                required
                value={fullName}
                onChange={(e) => setFullName(e.target.value)}
                className="w-full px-3 py-2 text-xs bg-slate-50 border border-slate-200 rounded-xl focus:outline-none focus:ring-2 focus:ring-indigo-500"
              />
            </div>
            <div>
              <label className="text-xs font-semibold text-slate-700 block mb-1">Student Roll / ID</label>
              <input
                type="text"
                required
                value={studentId}
                onChange={(e) => setStudentId(e.target.value)}
                className="w-full px-3 py-2 text-xs bg-slate-50 border border-slate-200 rounded-xl focus:outline-none focus:ring-2 focus:ring-indigo-500"
              />
            </div>
          </div>

          <div>
            <label className="text-xs font-semibold text-slate-700 block mb-1">Degree Title</label>
            <input
              type="text"
              required
              value={degree}
              onChange={(e) => setDegree(e.target.value)}
              className="w-full px-3 py-2 text-xs bg-slate-50 border border-slate-200 rounded-xl focus:outline-none focus:ring-2 focus:ring-indigo-500"
            />
          </div>

          <div>
            <label className="text-xs font-semibold text-slate-700 block mb-1">Major / Specialization</label>
            <input
              type="text"
              required
              value={major}
              onChange={(e) => setMajor(e.target.value)}
              className="w-full px-3 py-2 text-xs bg-slate-50 border border-slate-200 rounded-xl focus:outline-none focus:ring-2 focus:ring-indigo-500"
            />
          </div>

          <div className="grid grid-cols-2 gap-3">
            <div>
              <label className="text-xs font-semibold text-slate-700 block mb-1">Cumulative CGPA</label>
              <input
                type="number"
                step="0.01"
                min="0"
                max="10"
                required
                value={cgpa}
                onChange={(e) => setCgpa(e.target.value)}
                className="w-full px-3 py-2 text-xs bg-slate-50 border border-slate-200 rounded-xl focus:outline-none focus:ring-2 focus:ring-indigo-500"
              />
              <span className="text-[10px] text-indigo-600 font-semibold mt-0.5 block">
                {parseFloat(cgpa) >= 8.0 ? '✓ CGPA ≥ 8.0 (Qualified)' : '✗ CGPA < 8.0'}
              </span>
            </div>
            <div>
              <label className="text-xs font-semibold text-slate-700 block mb-1">Issuing University</label>
              <input
                type="text"
                required
                value={institutionName}
                onChange={(e) => setInstitutionName(e.target.value)}
                className="w-full px-3 py-2 text-xs bg-slate-50 border border-slate-200 rounded-xl focus:outline-none focus:ring-2 focus:ring-indigo-500"
              />
            </div>
          </div>

          {/* Feature Badge */}
          <div className="bg-indigo-50/70 border border-indigo-200 rounded-2xl p-3 flex items-start gap-2.5">
            <Sparkles className="w-4 h-4 text-indigo-600 flex-shrink-0 mt-0.5" />
            <p className="text-[11px] text-indigo-900 leading-tight">
              <strong>Auto QR Generator:</strong> Creating this student will immediately generate a cryptographically signed QR code with selective disclosure (&quot;CGPA ≥ 8.0: true&quot;).
            </p>
          </div>

          {/* Submit */}
          <div className="pt-2">
            <button
              type="submit"
              disabled={isSubmitting}
              className="w-full flex items-center justify-center gap-2 py-3 bg-indigo-600 hover:bg-indigo-700 text-white font-bold text-xs rounded-xl shadow-md transition disabled:opacity-50"
            >
              <QrCode className="w-4 h-4" />
              <span>{isSubmitting ? 'Creating & Generating QR...' : 'Create Student & Auto-Generate QR'}</span>
            </button>
          </div>
        </form>
      </div>
    </div>
  );
}
